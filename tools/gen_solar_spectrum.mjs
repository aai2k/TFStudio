/**
 * gen_solar_spectrum.mjs: write the built-in AM1.5G table to
 * src/utils/physics/solarSpectrumData.js from the ASTM G173-03 reference file.
 *
 * Source: ASTM G173-03 reference spectra derived from SMARTS 2.9.2, global
 * tilt (hemispherical, 37 deg sun-facing tilt), the third column of NREL's
 * ASTMG173.csv. The file ships with pvlib, which renames its header to
 * `wavelength,extraterrestrial,global,direct`; columns are read by position.
 * Irradiance is in W/m^2/nm, wavelength in nm.
 *
 * Method: G173 is taken as piecewise linear between its points. The table has
 * one row per 5 nm from 280 to 2500 nm, and the row at L is the mean of that
 * curve over [L - 2.5, L + 2.5] nm, cut at 280 nm where G173 starts. A mean
 * over the bin keeps the energy: the sum of row * 5 nm matches the integral of
 * G173 over the same range to the rounding of the printed values.
 *
 * The module is read back before it is written, and nothing is written if a
 * row read back differs from the one computed.
 *
 * The CSV is looked up in this order: TFS_G173_SOURCE, ../../reference/astm-g173/ASTMG173.csv.
 *
 * Usage: node tools/gen_solar_spectrum.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'utils', 'physics', 'solarSpectrumData.js');

const LAMBDA_MIN = 280;
const LAMBDA_MAX = 2500;
const BIN = 5;
const GLOBAL_TILT_COLUMN = 2;

function locateSource() {
    const candidates = [
        process.env.TFS_G173_SOURCE,
        path.resolve(ROOT, '..', '..', 'reference', 'astm-g173', 'ASTMG173.csv'),
    ].filter(Boolean);
    const found = candidates.find((p) => fs.existsSync(p));
    if (!found) throw new Error(`ASTMG173.csv not found. Looked in:\n  ${candidates.join('\n  ')}`);
    return found;
}

function readG173(file) {
    const rows = [];
    for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
        const cells = line.split(',');
        const lam = Number(cells[0]);
        const e = Number(cells[GLOBAL_TILT_COLUMN]);
        if (cells.length >= 4 && cells[0].trim() !== '' && Number.isFinite(lam) && Number.isFinite(e)) rows.push([lam, e]);
    }
    if (rows.length < 2000) throw new Error(`Expected about 2000 G173 rows, read ${rows.length}`);
    for (let i = 1; i < rows.length; i++) {
        if (!(rows[i][0] > rows[i - 1][0])) throw new Error(`G173 wavelengths not increasing at row ${i}`);
    }
    return rows;
}

/** Integral of the piecewise linear curve over [a, b] nm, in W/m^2. */
function integrate(rows, a, b) {
    let sum = 0;
    for (let i = 1; i < rows.length; i++) {
        const [x0, y0] = rows[i - 1];
        const [x1, y1] = rows[i];
        const lo = Math.max(a, x0);
        const hi = Math.min(b, x1);
        if (hi <= lo) continue;
        const slope = (y1 - y0) / (x1 - x0);
        const ylo = y0 + slope * (lo - x0);
        const yhi = y0 + slope * (hi - x0);
        sum += 0.5 * (ylo + yhi) * (hi - lo);
    }
    return sum;
}

function binned(rows) {
    const table = [];
    for (let lam = LAMBDA_MIN; lam <= LAMBDA_MAX; lam += BIN) {
        const a = Math.max(lam - BIN / 2, LAMBDA_MIN);
        const b = lam + BIN / 2;
        table.push([lam, Number((integrate(rows, a, b) / (b - a)).toPrecision(5))]);
    }
    return table;
}

function moduleText(table) {
    const rows = [];
    for (let i = 0; i < table.length; i += 5) {
        rows.push(table.slice(i, i + 5).map(([l, e]) => `[${l},${e}]`).join(','));
    }
    return `/**
 * ASTM G173-03 reference solar spectrum, AM1.5 global tilt (hemispherical,
 * 37 degree sun-facing tilt), W/m^2/nm. Generated by tools/gen_solar_spectrum.mjs
 * from NREL's ASTMG173.csv (SMARTS 2.9.2); do not edit by hand.
 *
 * One row [lambda_nm, E] per ${BIN} nm from ${LAMBDA_MIN} to ${LAMBDA_MAX} nm. Each row is the mean of the
 * G173 curve over the ${BIN} nm centred on lambda (cut at ${LAMBDA_MIN} nm), so the energy is kept.
 */
export const AM1_5G_5NM = [
${rows.join(',\n')},
];
`;
}

const table = binned(readG173(locateSource()));
const text = moduleText(table);

const ctx = { exports: {} };
new Function('exports', text.replace('export const', 'exports.AM1_5G_5NM ='))(ctx.exports);
const back = ctx.exports.AM1_5G_5NM;
if (back.length !== table.length || back.some(([l, e], i) => l !== table[i][0] || e !== table[i][1])) {
    throw new Error('Module read back differs from the computed table; nothing written.');
}
fs.writeFileSync(OUT, text);
console.log(`wrote ${table.length} rows to ${path.relative(ROOT, OUT)}`);
